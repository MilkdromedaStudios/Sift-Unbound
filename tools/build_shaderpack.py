#!/usr/bin/env python3
"""Builds Sift Unbound Shaders (an Iris shader pack) from shaderpack/.

The real GLSL lives in shaderpack/shaders/program and shaderpack/shaders/lib. Each dimension gets a folder of tiny
wrapper programs (named in dimension.properties) that set DIM_* / PROGRAM_* defines and include the shared code, so
the Overworld, the Nether, the End, the Sift and any other mod's dimension each get the right lighting.

It ships with every mod release (release.yml attaches the zip) and every CI build (an artifact), versioned with the mod.

Run from the repository root:
    python3 tools/build_shaderpack.py          # regenerate the wrappers and zip the pack into build/shaderpack/
"""
import os
import zipfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PACK = os.path.join(ROOT, "shaderpack")
SHADERS = os.path.join(PACK, "shaders")

DIMENSIONS = {  # folder -> defines ("" = the shaders/ root: the Overworld, and the fallback for every other dimension)
    "": ["DIM_OVERWORLD", "HAS_SHADOWS"],
    "world-1": ["DIM_NETHER"],
    "world1": ["DIM_END"],
    "sift": ["DIM_SIFT", "HAS_SHADOWS"],
}
LIT = {"gbuffers_terrain": "PROGRAM_TERRAIN", "gbuffers_block": "PROGRAM_BLOCK", "gbuffers_entities": "PROGRAM_ENTITIES",
       "gbuffers_hand": "PROGRAM_HAND", "gbuffers_water": "PROGRAM_WATER", "gbuffers_textured_lit": "PROGRAM_TEXTURED_LIT"}
UNLIT = {"gbuffers_basic": "PROGRAM_BASIC", "gbuffers_textured": "PROGRAM_TEXTURED", "gbuffers_skybasic": "PROGRAM_SKYBASIC",
         "gbuffers_skytextured": "PROGRAM_SKYTEXTURED", "gbuffers_clouds": "PROGRAM_CLOUDS", "gbuffers_weather": "PROGRAM_WEATHER",
         "gbuffers_spidereyes": "PROGRAM_EMISSIVE", "gbuffers_beaconbeam": "PROGRAM_EMISSIVE", "gbuffers_armor_glint": "PROGRAM_EMISSIVE"}


def wrapper(defines, source):
    lines = ["#version 120", "// Generated by tools/build_shaderpack.py: edit the shared file instead."]
    lines += [f"#define {d}" for d in defines]
    lines.append(f'#include "/program/{source}"')
    return "\n".join(lines) + "\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def gen_wrappers():
    for folder, dims in DIMENSIONS.items():
        out = os.path.join(SHADERS, folder)
        programs = [(name, define, "lit") for name, define in LIT.items()] + [(name, define, "unlit") for name, define in UNLIT.items()]
        if "HAS_SHADOWS" in dims:
            programs.append(("shadow", None, "shadow"))
        programs.append(("final", None, "final"))
        for name, define, source in programs:
            defines = dims + ([define] if define else [])
            for ext in ("vsh", "fsh"):
                write(os.path.join(out, f"{name}.{ext}"), wrapper(defines, f"{source}.{ext}"))


def zip_pack():
    props = open(os.path.join(ROOT, "gradle.properties")).read()
    version = next(line.split("=", 1)[1].strip() for line in props.splitlines() if line.startswith("mod_version="))
    dest_dir = os.path.join(ROOT, "build", "shaderpack")
    os.makedirs(dest_dir, exist_ok=True)
    dest = os.path.join(dest_dir, f"Sift-Unbound-Shaders-{version}.zip")
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(PACK):
            for name in sorted(files):
                full = os.path.join(base, name)
                z.write(full, os.path.relpath(full, PACK))
    return dest


if __name__ == "__main__":
    gen_wrappers()
    print("wrote", zip_pack())
